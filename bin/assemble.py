def centrifugal_blocks(loc_list, fun, l, sec, comp, lls, row, col0, factor=1, nblk=None, dls=None):
    '''
    NEW (2026-11-05): adds to loc_list the blocks of a centrifugal term (centrifugal = 1: operators.centrifugal_coriolis,
    centrifugal_inertia, centrifugal_entropy or, phase 2, centrifugal_diffusion and centrifugal_diffusion_ic; the Δl of
    centrifugal.dl_range) of the row degree l of section sec, for the unknown comp ('upol', 'utor', 'temp', 'bpol', 'btor',
    'bpol_ic' or 'btor_ic'), whose degrees are lls; col0 is the column of the first block of that unknown for the same
    position as the row, factor multiplies the blocks (-1 for the inertia in B and the viscous force in A), nblk is the
    size of a block (N1, or Nic in a conducting inner core) and dls the Δl to place (default centrifugal.dl_range; NEW
    2026-11-06: centrifugal.rotation_dl_range for operators.centrifugal_rotation)
    '''
    nblk = ut.N1 if nblk is None else nblk
    for i in (cf.dl_range(sec, comp) if dls is None else dls):
        if l + i in lls:
            mtx = fun(l, sec, comp, i)
            if np.isscalar(mtx[0]): continue   # nothing couples this Δl
            loc_list = ut.packit(loc_list, factor*mtx[0], row, col0 + mtx[1]*nblk)
    return loc_list



def main():

    warnings.simplefilter('ignore', ss.SparseEfficiencyWarning)


    comm  = MPI.COMM_WORLD
    sizas = comm.Get_size()
    rank  = comm.Get_rank()

    ll_flo = ut.ell( par.m, par.lmax, par.symm)[:2]  # the ell indices for the flow u

    # NEW (2026-11-06, as conductive_IC): a thin wall (or the resolved mantle) next to a slipping fluid gets the u×B0 terms of
    # condition C.I (bc_b_slip)
    if rank == 0 and (ut.twa_slips('outer') or ut.twa_slips('inner') or ut.mantle_slips()):
        pm = par.ViscosD/par.MagnetD
        ratio = '%.1e' % (pm*abs(par.itau)/par.Gaspard if par.Gaspard else pm)
        print('Note: fluid slipping along a conducting wall: the tangential electric field continued into the wall in its own '
              'frame (condition C.I of Rekier et al. 2023), valid while the viscous layer left out is thin against the magnetic '
              'skin depth (%s = %s << 1)' % ('Pm |itau|/Gaspard' if par.Gaspard else 'Pm', ratio))

    if rank == 0:
        alltop, allbot = ll_flo
    else:
        alltop = None
        allbot = None

    nb = int((par.lmax - par.m + 1)/2)  # number of block rows per quarter
    bpp = int(nb/sizas)     # block rows per process

    if (par.lmax - par.m + 1) % (2*sizas) != 0:  # otherwise Scatter drops l's (one rank) or fails on rank 0 only and the others hang
        if rank == 0:
            print('lmax - m + 1 must be a multiple of 2*ncpus (number of MPI ranks), got', par.lmax - par.m + 1, 'and', sizas)
        sys.exit(1)

    loc_top = np.zeros(bpp, dtype=int)
    loc_bot = np.zeros(bpp, dtype=int)

    # split the vectors with l values and distribute to all cpu's (ranks)
    comm.Scatter(alltop, loc_top, root=0)
    comm.Scatter(allbot, loc_bot, root=0)

    if par.magnetic:  # NEW (2026-10-28): the l's of the magnetic field, f with the l's of P if B0 is symmetric, of T if antisymmetric
        ll_mag = ut.ell( par.m, par.lmax, ut.bsymm)[:2]
        loc_mag_f, loc_mag_g = (loc_top, loc_bot) if ut.symmB0 == 1 else (loc_bot, loc_top)



    if par.forcing == 6: # -------------------------------------------------- Buffett 2010 ICB radial velocity forcing

        if rank == 0:
            print('Buffett 2010 ICB radial velocity forcing')

            if par.m == 1 and par.symm == -1 and par.ricb > 0 and par.bci in (0, 1):  # FIX (2026-11-06): ricb > 0 (as conductive_IC)

                l = 2 # goes with the poloidals (2curl eqs) at the rows for the ICB boundary conditions

                pos = ut.N1*np.where(alltop==l)[0][0]  # pos should be zero

                hft = 0.0025 # Inner core hydrostating flattening
                C   = (1j)*(2/3)*np.sqrt(6)*hft*par.ricb

                P   = ( par.ricb/(l*(l+1)) ) * C * par.forcing_amplitude_icb

                # FIX (2026-11-06): the ICB's P row of bc_u_spherical (pos + 2; it went to the CMB's, pos), as conductive_IC
                # 35fff71. Only P is given: the second ICB row of bc_u_spherical already holds the whole condition for P != 0,
                # zero tangential velocity (no-slip, (rP)'/r + P (ln rho0)' = 0) or zero tangential stress (stress-free), so its
                # right-hand side is 0. conductive_IC writes P' = dP = -P/ricb and P'' = (2 - L) P/ricb^2 there, the same
                # conditions in its rows P' = 0 and P'' = 0; here those values made the ICB slip.
                row  = [pos + 2]
                bdat = [P]

                B = ss.csr_matrix( ( bdat, (row, np.zeros(1)) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('Buffet2010 forcing requires m = 1, symm = -1, ricb > 0, bci = 0 or 1')


    elif par.forcing == 7: # ------------------------------------------------------------ longitudinal libration forcing

        # libration in longitude as a boundary flow forcing
        if rank == 0:

            if par.m == 0 and par.symm == 1 and par.bci == 1 and par.bco == 1:

                print('--------------------------------------------')
                print('Longitudinal libration - axial forcing (m = 0)')
                print('--------------------------------------------')

                l = 1   # l=1 Toroidal boundary forcing

                pos = ut.n + ut.N1*np.where(allbot==l)[0][0]
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                # forcing amplitude is (1/2) of libration amplitude in radians
                C_icb = 1j* par.forcing_frequency * par.forcing_amplitude_icb * par.ricb / 2
                C_cmb = 1j* par.forcing_frequency * par.forcing_amplitude_cmb / 2 # rcmb is 1

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            elif par.m == 2 and par.symm == 1 and par.bci == 1 and par.bco == 1:

                print('--------------------------------------------')
                print('Longitudinal libration - radial forcing (m = {:n})'.format(np.sign(par.forcing_frequency)*par.m))
                print('--------------------------------------------')

                l = 2  # up to first order the moving boundary corresponds to the degree 2 components.
                L = l * (l + 1)

                pos = ut.N1 * np.where(alltop == l)[0][0]

                # amplitude for the l=2 components
                C_cmb = -par.forcing_frequency / L * par.forcing_amplitude_cmb
                C_icb = -par.forcing_frequency / L * par.forcing_amplitude_icb * (par.ricb ** 2)

                # FIX (2026-11-06): P at the CMB (row pos) and at the ICB (row pos + 2, bc_u_spherical), as conductive_IC
                # 35fff71; C_icb went to the CMB's P' row (pos + 1). No inner wall in a full sphere.
                row  = [pos] + ([pos + 2] if par.ricb > 0 else [])
                bdat = [C_cmb] + ([C_icb] if par.ricb > 0 else [])

                B = ss.csr_matrix((bdat, (row, np.zeros(len(row)))), shape=(ut.sizmat, 1))
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print(' ** Longitudinal libration requires m = 0, symm = 1 and no-slip boundaries **')




    elif par.forcing == 9: # --------------------------------------------------------------- m=2 radial velocity forcing

        # m=2 radial velocity forcing at the icb or cmb, l=2 Poloidal scalar only, equatorially symmetric.
        if rank == 0:

            print('--------------------------------------------')
            print(' m=2 radial velocity forcing                ')
            print('--------------------------------------------')

            if (par.symm == 1 and par.m==2) and (par.bci==1):

                l = 2   #
                L = l*(l+1)

                pos = ut.N1*np.where(alltop==l)[0][0]

                #C_icb = L*par.m*par.forcing_frequency*par.forcing_amplitude_icb/par.ricb  # to be checked
                #C_cmb = L*par.m*par.forcing_frequency*par.forcing_amplitude_cmb

                # forcing amplitude is the radial velocity amplitude
                C_icb = par.forcing_amplitude_icb * par.ricb / L
                C_cmb = par.forcing_amplitude_cmb * ut.rcmb / L

                # FIX (2026-11-06): P at the CMB (row pos) and at the ICB (row pos + 2, bc_u_spherical), as conductive_IC
                # 35fff71; C_icb went to the CMB's P' row (pos + 1). No inner wall in a full sphere.
                row  = [pos] + ([pos + 2] if par.ricb > 0 else [])
                bdat = [C_cmb] + ([C_icb] if par.ricb > 0 else [])

                B = ss.csr_matrix( ( bdat, (row, np.zeros(len(row))) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('This boundary flow forcing needs symm = 1 and m = 2 and bci = 1')

    elif par.forcing == 10: # --------------------------------------------------------------- m=2 radial velocity forcing

        # Order m radial velocity forcing at the icb or cmb, l=m poloidal scalar only, equatorially symmetric.
        if rank == 0:

            print('--------------------------------------------')
            print(' m=%d radial forcing                        ' %par.m)
            print('--------------------------------------------')

            if ( par.symm == 1 ):

                l = par.m   #
                L = l*(l+1)

                pos = ut.N1*np.where(alltop==l)[0][0]
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                #C_icb = L*par.m*par.forcing_frequency*par.forcing_amplitude_icb/par.ricb  # to be checked
                #C_cmb = L*par.m*par.forcing_frequency*par.forcing_amplitude_cmb

                # forcing amplitude is the radial velocity amplitude
                C_icb = 0.0
                C_cmb = 1./L * 1.0

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('This boundary flow forcing needs symm = 1')

    elif par.forcing == 11: # -------------------------------------------- random Reynolds-stress body force (convection)

        # rsf_nsamp realisations of the random force, one per column (bin/reynolds_stress.py)
        if rank == 0:

            try:
                import reynolds_stress as rs
                B = rs.rhs(par.rsf_nsamp, par.rsf_seed)
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)
            except BaseException as e:  # a parameter error (sys.exit) or any other: stop every rank, not only this one
                print(e if isinstance(e, SystemExit) else repr(e), flush=True)
                comm.Abort(1)

    elif par.forcing == 13: # ------------------------------------------ latitudinal entropy at the inner wall (m = 0)

        # s = forcing_amplitude_icb P2(cos θ) at r = ricb (bci_thermal = 0), or ds/dr = forcing_amplitude_icb P2(cos θ)
        # (bci_thermal = 1): the right-hand side of the inner-wall entropy row of l = 2. The field is (coefficient) Y + c.c.,
        # so the coefficient is half the amplitude.
        if rank == 0:

            if par.m != 0 or par.symm != 1 or par.ricb == 0 or par.thermal == 0 or par.ThermaD == 0 or par.forcing_amplitude_icb == 0:
                print('forcing 13 needs m = 0, symm = 1, ricb > 0, thermal = 1, ThermaD > 0 and forcing_amplitude_icb != 0', flush=True)
                comm.Abort(1)
            if par.forcing_frequency == 0 and par.bci == 0 and par.bco == 0:  # a rigid rotation would solve A x = 0
                print('forcing 13 with forcing_frequency = 0 needs a no-slip wall (bci = 1 or bco = 1)', flush=True)
                comm.Abort(1)

            row = ut.offset['h'] + int(ut.N1*(2 - ut.m_top)/2) + 1  # entropy block, l = 2, inner-wall row (bc_theta_spherical)
            B = ss.csr_matrix( ( [par.forcing_amplitude_icb/2], ([row], [0]) ), shape=(ut.sizmat,1) )
            np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)


    elif par.forcing == 14: # ------------- Eccentricity or Obliquity tide forcing, (m, symm) = {(0, 1), (1, -1), (2, 1)}, l=2 radial velocity forcing

        # uᵣ = forcing_amplitude Y_2^m at the walls (docs/tidal-forcing.md): the right-hand side of the P = ... rows of l = 2
        # (bc_u_spherical: the outer wall first, then the inner one), P = A r/L. The no-slip rows are kept.
        if rank == 0:
            tides = { (0, 1): 'Eccentricity tide (l,m)=(2,0) radial velocity forcing (symmetric)',
                      (1, -1): 'Obliquity tide (l,m)=(2,1) radial velocity forcing (antisymmetric)',
                      (2, 1): 'Eccentricity tide (l,m)=(2,2) radial velocity forcing (symmetric)' }
            if (par.m, par.symm) not in tides:
                print('forcing 14 needs (m, symm) = (0, 1), (1, -1) or (2, 1)', flush=True)
                comm.Abort(1)
            if par.bco != 1 or par.bci != 1:
                print('forcing 14 needs bco = bci = 1 (also in a full sphere)', flush=True)
                comm.Abort(1)
            print('-'*(len(tides[(par.m, par.symm)]) + 2))
            print(' ' + tides[(par.m, par.symm)])
            print('-'*(len(tides[(par.m, par.symm)]) + 2))

            l = 2
            L = l*(l+1)
            pos = ut.N1*np.where(alltop==l)[0][0]

            # forcing amplitude is the radial velocity amplitude
            row = [ pos ]
            bdat = [ par.forcing_amplitude_cmb * ut.rcmb / L ]
            if par.ricb > 0:  # no inner wall in a full sphere
                row.append( pos + 2 )
                bdat.append( par.forcing_amplitude_icb * par.ricb / L )

            B = ss.csr_matrix( ( bdat, (row, np.zeros(len(row))) ), shape=(ut.sizmat,1) )
            np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

    if rank == 0:
        tic = timer()
    loc_list = [[], [], []]  # this rank's A entries, as lists of (data, row, col) arrays



    # ------------------------------------------------------------------------------------------------------------------------------------------------
    # -------------------------------------------------------------------------------------------------------------- A matrix, 2curl hydro (section u)
    # ------------------------------------------------------------------------------------------------------------------------------------------------
    for k,l in enumerate(loc_top if par.hydro else []): # 2curl hydro eqs (NEW 2026-11-06: none with hydro = 0)

        col0 = ( rank*bpp + k )* ut.N1
        row  = col0


        # Poloidal velocity terms (upol) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 2curl (section u), upol
        # ----------------------------------------------------------------------------------------------------------
        basecol = 0

        # Physics ----------------------------------------------
        iwu  = op.inertia(l,'u','upol',0)*1j*ut.wf
        cori = op.coriolis(l,'u','upol',0)[0]
        visc = op.viscous_diffusion(l,'u','upol',0)
        mtx = iwu + cori - visc

        # ------------------------------------------------------
        col = basecol + col0
        loc_list = ut.packit(loc_list, mtx, row, col)

        if par.diff_rot : 
            for i in dr.dl_range('u','upol') :   # Δl = 0, ±2, ..., ±n_max (the highest degree of ΔΩ)
                if l+i in ll_flo[0] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'u','upol',i)
                    if np.isscalar(mtx[0]): continue   # no degree of ΔΩ couples this Δl
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)

        if par.centrifugal :  # NEW (2026-11-05): the Coriolis force of the deformed body, 2 Gaspard (z̃ - ẑ)×w, Δl = 0, ±2
            loc_list = centrifugal_blocks( loc_list, op.centrifugal_coriolis, l, 'u', 'upol', ll_flo[0], row, basecol + col0)
            if par.ViscosD > 0:  # NEW (2026-11-05, phase 2): the metric part of the viscous force, minus (as -visc)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_diffusion, l, 'u', 'upol', ll_flo[0], row, basecol + col0, -1)
            if par.diff_rot:  # NEW (2026-11-06, phase 2): the metric part of the differential rotation's force (as diff_rot's)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_rotation, l, 'u', 'upol', ll_flo[0], row, basecol + col0,
                                               dls=cf.rotation_dl_range('u', 'upol'))


        # Toroidal velocity terms (utor) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 2curl (section u), utor
        # ----------------------------------------------------------------------------------------------------------
        basecol = nb*ut.N1

        for i in [-1,1]:

            if l+i in ll_flo[1] :

                # Physics ---------------------------------------
                mtx = op.coriolis(l,'u','utor',i)
                # -----------------------------------------------
                col = basecol + col0 + mtx[1] * ut.N1
                loc_list = ut.packit( loc_list, mtx[0], row, col)

        if par.diff_rot : 
            for i in dr.dl_range('u','utor') :   # Δl = ±1, ±3, ..., ±(n_max + 1)
                if l+i in ll_flo[1] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'u','utor',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)

        if par.centrifugal :  # NEW (2026-11-05): Δl = ±1, ±3
            loc_list = centrifugal_blocks( loc_list, op.centrifugal_coriolis, l, 'u', 'utor', ll_flo[1], row, basecol + col0)
            if par.ViscosD > 0:  # NEW (2026-11-05, phase 2): the metric part of the viscous force (Δl = ±1)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_diffusion, l, 'u', 'utor', ll_flo[1], row, basecol + col0, -1)
            if par.diff_rot:  # NEW (2026-11-06, phase 2): the metric part of the differential rotation's force (as diff_rot's)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_rotation, l, 'u', 'utor', ll_flo[1], row, basecol + col0,
                                               dls=cf.rotation_dl_range('u', 'utor'))



        if par.thermal == 1 : # include the buoyancy force

            # Buoyancy force, theta (temperature) terms ------------------------------------------------------------
            # --------------------------------------------------------------------------- A, 2curl (section u), temp
            # ------------------------------------------------------------------------------------------------------
            basecol = 2*nb*ut.N1

            # Physics ------------------------------------
            mtx = -1 * op.buoyancy(l,'u','',0)
            # --------------------------------------------
            col = basecol + col0
            loc_list = ut.packit( loc_list, mtx, row, col)




        if par.magnetic == 1:  # NEW (2026-10-28): Lorentz force -------------------------------------------------------
            # ------------------------------------------------------------------------- A, 2curl (section u), bpol, btor
            for comp, sec in [ ('bpol', 'f'), ('btor', 'g') ]:
                for i in ut.mag_dl:   # the couplings of a poloidal B0 and of a toroidal one (operators.lorentz returns 0 for the others; NEW 2026-10-30: ut.mag_dl)
                    if l+i in ll_mag[0 if comp == 'bpol' else 1]:
                        mtx = op.lorentz(l,'u',comp,i)
                        if np.isscalar(mtx[0]): continue
                        col = ut.offset[sec] + col0 + mtx[1] * ut.N1
                        loc_list = ut.packit( loc_list, mtx[0], row, col)
                if par.centrifugal:  # NEW (2026-11-05, phase 1b): the metric part of the Lorentz force of the deformed body (Δl up to nmax + 3)
                    for i in cf.magnetic_dl_range():
                        if l+i in ll_mag[0 if comp == 'bpol' else 1]:
                            mtx = op.centrifugal_magnetic(l,'u',comp,i)
                            if np.isscalar(mtx[0]): continue
                            col = ut.offset[sec] + col0 + mtx[1] * ut.N1
                            loc_list = ut.packit( loc_list, mtx[0], row, col)


        # ----------------------------------------------------------------------------------------------------------
        # ---------------------------- include poloidal velocity boundary conditions and update loc_list (section u)
        # ----------------------------------------------------------------------------------------------------------
        bc_u_list = bc_u_spherical( l, 'section_u' )
        for q in [0,1,2]:
            loc_list[q].append( bc_u_list[q] )
        if par.centrifugal and par.ViscosD > 0:  # NEW (2026-11-05, phase 2): the metric parts of the stress-free rows
            bc_u_list = bc_u_centrifugal( l, 'section_u', ll_flo )
            for q in [0,1,2]:
                loc_list[q].append( bc_u_list[q] )
        # ----------------------------------------------------------------------------------------------------------



    # ------------------------------------------------------------------------------------------------------------------------------------------------
    # -------------------------------------------------------------------------------------------------------------- A matrix, 1curl hydro (section v)
    # ------------------------------------------------------------------------------------------------------------------------------------------------
    for k,l in enumerate(loc_bot if par.hydro else []): # 1curl Navier-Stokes equations (none with hydro = 0)

        col0 = (rank*bpp + k )* ut.N1
        row  = col0 + nb*ut.N1


        # Poloidal velocity terms (upol) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 1curl (section v), upol
        # ----------------------------------------------------------------------------------------------------------
        basecol = 0

        for i in [ -1, 1 ]:

            if l+i in ll_flo[0]:  # for upol, so we use ll_flo[0]

                # Physics ---------------------------------------
                mtx = op.coriolis(l,'v','upol', i)
                # -----------------------------------------------
                col = basecol + col0 + mtx[1]*ut.N1
                loc_list = ut.packit( loc_list, mtx[0], row, col)
            
        if par.diff_rot : 
            for i in dr.dl_range('v','upol') :
                if l+i in ll_flo[0] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'v','upol',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)

        if par.centrifugal :  # NEW (2026-11-05): the Coriolis force of the deformed body, Δl = ±1, ±3
            loc_list = centrifugal_blocks( loc_list, op.centrifugal_coriolis, l, 'v', 'upol', ll_flo[0], row, basecol + col0)
            if par.ViscosD > 0:  # NEW (2026-11-05, phase 2): the metric part of the viscous force (Δl = ±1)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_diffusion, l, 'v', 'upol', ll_flo[0], row, basecol + col0, -1)
            if par.diff_rot:  # NEW (2026-11-06, phase 2): the metric part of the differential rotation's force (as diff_rot's)
                loc_list = centrifugal_blocks( loc_list, op.centrifugal_rotation, l, 'v', 'upol', ll_flo[0], row, basecol + col0,
                                               dls=cf.rotation_dl_range('v', 'upol'))


        # Toroidal velocity terms ----------------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 1curl (section v), utor
        # ----------------------------------------------------------------------------------------------------------
        basecol = nb*ut.N1

        # Physics ------------------------------------
        iwu  = op.inertia(l,'v','utor',0)*1j*ut.wf
        cori = op.coriolis(l,'v','utor',0)[0]
        visc = op.viscous_diffusion(l,'v','utor',0)
        mtx = iwu + cori - visc
        # --------------------------------------------
        col = basecol + col0
        loc_list = ut.packit( loc_list, mtx, row, col)


        if par.diff_rot : 
            for i in dr.dl_range('v','utor') :
                if l+i in ll_flo[1] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'v','utor',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
