#!/usr/bin/env python3
'''
kore assembles

Use as:
mpiexec -n ncpus  ./bin/assemble.py
ncpus should match the value in the parameters.py file

This program takes the block matrices generated by submatrices.py
and assembles the matrix A, the matrix B, or the forcing vector.
'''

from timeit import default_timer as timer
t_start = timer()  # wall clock from here, before scipy/utils are imported
import scipy.sparse.linalg as ssl
import scipy.sparse as ss
from mpi4py import MPI
import numpy as np
import warnings
import sys

import bc_variables as bv
from parameters import par
import utils as ut
import operators as op
import diff_rot as dr
import radial_profiles as rap

def main():

    warnings.simplefilter('ignore', ss.SparseEfficiencyWarning)


    comm  = MPI.COMM_WORLD
    sizas = comm.Get_size()
    rank  = comm.Get_rank()

    ll_flo = ut.ell( par.m, par.lmax, par.symm)[:2]  # the ell indices for the flow u

    if rank == 0:
        alltop, allbot = ll_flo
    else:
        alltop = None
        allbot = None

    nb = int((par.lmax - par.m + 1)/2)  # number of block rows per quarter
    bpp = int(nb/sizas)     # block rows per process

    if (par.lmax - par.m + 1) % (2*sizas) != 0:  # otherwise Scatter drops l's (one rank) or fails on rank 0 only and the others hang
        if rank == 0:
            print('lmax - m + 1 must be a multiple of 2*ncpus (number of MPI ranks), got', par.lmax - par.m + 1, 'and', sizas)
        sys.exit(1)

    loc_top = np.zeros(bpp, dtype=int)
    loc_bot = np.zeros(bpp, dtype=int)

    # split the vectors with l values and distribute to all cpu's (ranks)
    comm.Scatter(alltop, loc_top, root=0)
    comm.Scatter(allbot, loc_bot, root=0)

    if par.magnetic:  # NEW (2026-10-28): the l's of the magnetic field, f with the l's of P if B0 is symmetric, of T if antisymmetric
        ll_mag = ut.ell( par.m, par.lmax, ut.bsymm)[:2]
        loc_mag_f, loc_mag_g = (loc_top, loc_bot) if ut.symmB0 == 1 else (loc_bot, loc_top)



    if par.forcing == 6: # -------------------------------------------------- Buffett 2010 ICB radial velocity forcing

        if rank == 0:
            print('Buffett 2010 ICB radial velocity forcing')

            if par.m == 1 and par.symm == -1:

                l = 2 # goes with the poloidals (2curl eqs) at the rows for the ICB boundary conditions

                pos = ut.N1*np.where(alltop==l)[0][0]  # pos should be zero
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                hft = 0.0025 # Inner core hydrostating flattening
                C   = (1j)*(2/3)*np.sqrt(6)*hft*par.ricb

                P   = ( par.ricb/(l*(l+1)) ) * C * par.forcing_amplitude_icb
                dP  = -P/par.ricb
                d2P = (2-l*(l+1))*P/(par.ricb**2)

                if par.bci == 0: # stress-free
                    #bdat = -1j*ut.wf*np.array([P, d2P])
                    bdat = np.array([P, d2P])

                elif par.bci == 1: # no-slip
                    #bdat = -1j*ut.wf*np.array([P,  dP])
                    bdat = np.array([P,  dP])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('Buffet2010 forcing requires m = 1, symm = -1')


    elif par.forcing == 7: # ------------------------------------------------------------ longitudinal libration forcing

        # libration in longitude as a boundary flow forcing
        if rank == 0:

            if par.m == 0 and par.symm == 1 and par.bci == 1 and par.bco == 1:

                print('--------------------------------------------')
                print('Longitudinal libration - axial forcing (m = 0)')
                print('--------------------------------------------')

                l = 1   # l=1 Toroidal boundary forcing

                pos = ut.n + ut.N1*np.where(allbot==l)[0][0]
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                # forcing amplitude is (1/2) of libration amplitude in radians
                C_icb = 1j* par.forcing_frequency * par.forcing_amplitude_icb * par.ricb / 2
                C_cmb = 1j* par.forcing_frequency * par.forcing_amplitude_cmb / 2 # rcmb is 1

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            elif par.m == 2 and par.symm == 1 and par.bci == 1 and par.bco == 1:

                print('--------------------------------------------')
                print('Longitudinal libration - radial forcing (m = {:n})'.format(np.sign(par.forcing_frequency)*par.m))
                print('--------------------------------------------')

                l = 2  # up to first order the moving boundary corresponds to the degree 2 components.
                L = l * (l + 1)

                pos = ut.N1 * np.where(alltop == l)[0][0]
                row = np.arange(pos, pos + 2)
                col = np.zeros(2)

                # amplitude for the l=2 components
                C_cmb = -par.forcing_frequency / L * par.forcing_amplitude_cmb
                C_icb = -par.forcing_frequency / L * par.forcing_amplitude_icb * (par.ricb ** 2)

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix((bdat, (row, col)), shape=(ut.sizmat, 1))
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print(' ** Longitudinal libration requires m = 0, symm = 1 and no-slip boundaries **')




    elif par.forcing == 9: # --------------------------------------------------------------- m=2 radial velocity forcing

        # m=2 radial velocity forcing at the icb or cmb, l=2 Poloidal scalar only, equatorially symmetric.
        if rank == 0:

            print('--------------------------------------------')
            print(' m=2 radial velocity forcing                ')
            print('--------------------------------------------')

            if (par.symm == 1 and par.m==2) and (par.bci==1):

                l = 2   #
                L = l*(l+1)

                pos = ut.N1*np.where(alltop==l)[0][0]
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                #C_icb = L*par.m*par.forcing_frequency*par.forcing_amplitude_icb/par.ricb  # to be checked
                #C_cmb = L*par.m*par.forcing_frequency*par.forcing_amplitude_cmb

                # forcing amplitude is the radial velocity amplitude
                C_icb = par.forcing_amplitude_icb * par.ricb / L
                C_cmb = par.forcing_amplitude_cmb * ut.rcmb / L

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('This boundary flow forcing needs symm = 1 and m = 2 and bci = 1')

    elif par.forcing == 10: # --------------------------------------------------------------- m=2 radial velocity forcing

        # Order m radial velocity forcing at the icb or cmb, l=m poloidal scalar only, equatorially symmetric.
        if rank == 0:

            print('--------------------------------------------')
            print(' m=%d radial forcing                        ' %par.m)
            print('--------------------------------------------')

            if ( par.symm == 1 ):

                l = par.m   #
                L = l*(l+1)

                pos = ut.N1*np.where(alltop==l)[0][0]
                row = np.arange(pos,pos+2)
                col = np.zeros(2)

                #C_icb = L*par.m*par.forcing_frequency*par.forcing_amplitude_icb/par.ricb  # to be checked
                #C_cmb = L*par.m*par.forcing_frequency*par.forcing_amplitude_cmb

                # forcing amplitude is the radial velocity amplitude
                C_icb = 0.0
                C_cmb = 1./L * 1.0

                bdat = np.array([C_cmb, C_icb])

                B = ss.csr_matrix( ( bdat, (row,col) ), shape=(ut.sizmat,1) )
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)

            else:

                print('This boundary flow forcing needs symm = 1')

    elif par.forcing == 11: # -------------------------------------------- random Reynolds-stress body force (convection)

        # rsf_nsamp realisations of the random force, one per column (bin/reynolds_stress.py)
        if rank == 0:

            try:
                import reynolds_stress as rs
                B = rs.rhs(par.rsf_nsamp, par.rsf_seed)
                np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)
            except BaseException as e:  # a parameter error (sys.exit) or any other: stop every rank, not only this one
                print(e if isinstance(e, SystemExit) else repr(e), flush=True)
                comm.Abort(1)

    elif par.forcing == 13: # ------------------------------------------ latitudinal entropy at the inner wall (m = 0)

        # s = forcing_amplitude_icb P2(cos θ) at r = ricb (bci_thermal = 0), or ds/dr = forcing_amplitude_icb P2(cos θ)
        # (bci_thermal = 1): the right-hand side of the inner-wall entropy row of l = 2. The field is (coefficient) Y + c.c.,
        # so the coefficient is half the amplitude.
        if rank == 0:

            if par.m != 0 or par.symm != 1 or par.ricb == 0 or par.thermal == 0 or par.ThermaD == 0 or par.forcing_amplitude_icb == 0:
                print('forcing 13 needs m = 0, symm = 1, ricb > 0, thermal = 1, ThermaD > 0 and forcing_amplitude_icb != 0', flush=True)
                comm.Abort(1)
            if par.forcing_frequency == 0 and par.bci == 0 and par.bco == 0:  # a rigid rotation would solve A x = 0
                print('forcing 13 with forcing_frequency = 0 needs a no-slip wall (bci = 1 or bco = 1)', flush=True)
                comm.Abort(1)

            row = 2*ut.n + int(ut.N1*(2 - ut.m_top)/2) + 1  # entropy block, l = 2, inner-wall row (bc_theta_spherical)
            B = ss.csr_matrix( ( [par.forcing_amplitude_icb/2], ([row], [0]) ), shape=(ut.sizmat,1) )
            np.savez('B_forced.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)



    if rank == 0:
        tic = timer()
    loc_list = [[], [], []]  # this rank's A entries, as lists of (data, row, col) arrays



    # ------------------------------------------------------------------------------------------------------------------------------------------------
    # -------------------------------------------------------------------------------------------------------------- A matrix, 2curl hydro (section u)
    # ------------------------------------------------------------------------------------------------------------------------------------------------
    for k,l in enumerate(loc_top): # 2curl hydro eqs

        col0 = ( rank*bpp + k )* ut.N1
        row  = col0


        # Poloidal velocity terms (upol) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 2curl (section u), upol
        # ----------------------------------------------------------------------------------------------------------
        basecol = 0

        # Physics ----------------------------------------------
        iwu  = op.inertia(l,'u','upol',0)*1j*ut.wf
        cori = op.coriolis(l,'u','upol',0)[0]
        visc = op.viscous_diffusion(l,'u','upol',0)
        mtx = iwu + cori - visc

        # ------------------------------------------------------
        col = basecol + col0
        loc_list = ut.packit(loc_list, mtx, row, col)

        if par.diff_rot : 
            for i in dr.dl_range('u','upol') :   # Δl = 0, ±2, ..., ±n_max (the highest degree of ΔΩ)
                if l+i in ll_flo[0] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'u','upol',i)
                    if np.isscalar(mtx[0]): continue   # no degree of ΔΩ couples this Δl
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)


        # Toroidal velocity terms (utor) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 2curl (section u), utor
        # ----------------------------------------------------------------------------------------------------------
        basecol = nb*ut.N1

        for i in [-1,1]:

            if l+i in ll_flo[1] :

                # Physics ---------------------------------------
                mtx = op.coriolis(l,'u','utor',i)
                # -----------------------------------------------
                col = basecol + col0 + mtx[1] * ut.N1
                loc_list = ut.packit( loc_list, mtx[0], row, col)

        if par.diff_rot : 
            for i in dr.dl_range('u','utor') :   # Δl = ±1, ±3, ..., ±(n_max + 1)
                if l+i in ll_flo[1] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'u','utor',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)



        if par.thermal == 1 : # include the buoyancy force

            # Buoyancy force, theta (temperature) terms ------------------------------------------------------------
            # --------------------------------------------------------------------------- A, 2curl (section u), temp
            # ------------------------------------------------------------------------------------------------------
            basecol = 2*nb*ut.N1

            # Physics ------------------------------------
            mtx = -1 * op.buoyancy(l,'u','',0)
            # --------------------------------------------
            col = basecol + col0
            loc_list = ut.packit( loc_list, mtx, row, col)




        if par.magnetic == 1:  # NEW (2026-10-28): Lorentz force -------------------------------------------------------
            # ------------------------------------------------------------------------- A, 2curl (section u), bpol, btor
            for comp, sec in [ ('bpol', 'f'), ('btor', 'g') ]:
                for i in ut.mag_dl:   # the couplings of a poloidal B0 and of a toroidal one (operators.lorentz returns 0 for the others; NEW 2026-10-30: ut.mag_dl)
                    if l+i in ll_mag[0 if comp == 'bpol' else 1]:
                        mtx = op.lorentz(l,'u',comp,i)
                        if np.isscalar(mtx[0]): continue
                        col = ut.offset[sec] + col0 + mtx[1] * ut.N1
                        loc_list = ut.packit( loc_list, mtx[0], row, col)


        # ----------------------------------------------------------------------------------------------------------
        # ---------------------------- include poloidal velocity boundary conditions and update loc_list (section u)
        # ----------------------------------------------------------------------------------------------------------
        bc_u_list = bc_u_spherical( l, 'section_u' )
        for q in [0,1,2]:
            loc_list[q].append( bc_u_list[q] )
        # ----------------------------------------------------------------------------------------------------------



    # ------------------------------------------------------------------------------------------------------------------------------------------------
    # -------------------------------------------------------------------------------------------------------------- A matrix, 1curl hydro (section v)
    # ------------------------------------------------------------------------------------------------------------------------------------------------
    for k,l in enumerate(loc_bot): # 1curl Navier-Stokes equations

        col0 = (rank*bpp + k )* ut.N1
        row  = col0 + nb*ut.N1


        # Poloidal velocity terms (upol) ---------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 1curl (section v), upol
        # ----------------------------------------------------------------------------------------------------------
        basecol = 0

        for i in [ -1, 1 ]:

            if l+i in ll_flo[0]:  # for upol, so we use ll_flo[0]

                # Physics ---------------------------------------
                mtx = op.coriolis(l,'v','upol', i)
                # -----------------------------------------------
                col = basecol + col0 + mtx[1]*ut.N1
                loc_list = ut.packit( loc_list, mtx[0], row, col)
            
        if par.diff_rot : 
            for i in dr.dl_range('v','upol') :
                if l+i in ll_flo[0] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'v','upol',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)


        # Toroidal velocity terms ----------------------------------------------------------------------------------
        # ------------------------------------------------------------------------------- A, 1curl (section v), utor
        # ----------------------------------------------------------------------------------------------------------
        basecol = nb*ut.N1

        # Physics ------------------------------------
        iwu  = op.inertia(l,'v','utor',0)*1j*ut.wf
        cori = op.coriolis(l,'v','utor',0)[0]
        visc = op.viscous_diffusion(l,'v','utor',0)
        mtx = iwu + cori - visc
        # --------------------------------------------
        col = basecol + col0
        loc_list = ut.packit( loc_list, mtx, row, col)


        if par.diff_rot : 
            for i in dr.dl_range('v','utor') :
                if l+i in ll_flo[1] :
                    # Physics ---------------------------------------
                    mtx = op.differential_rotation(l,'v','utor',i)
                    if np.isscalar(mtx[0]): continue
                    # -----------------------------------------------
                    col = basecol + col0 + mtx[1] * ut.N1
                    loc_list = ut.packit( loc_list, mtx[0], row, col)




        if par.magnetic == 1:  # NEW (2026-10-28): Lorentz force -------------------------------------------------------
            # ------------------------------------------------------------------------- A, 1curl (section v), bpol, btor
            for comp, sec in [ ('bpol', 'f'), ('btor', 'g') ]:
                for i in ut.mag_dl:   # (NEW 2026-10-30: ut.mag_dl)
                    if l+i in ll_mag[0 if comp == 'bpol' else 1]:
                        mtx = op.lorentz(l,'v',comp,i)
                        if np.isscalar(mtx[0]): continue
                        col = ut.offset[sec] + col0 + mtx[1] * ut.N1
                        loc_list = ut.packit( loc_list, mtx[0], row, col)


        # ----------------------------------------------------------------------------------------------------------
        # ----------------------------------------------------------------------------- No temp or comp terms needed
        # ----------------------------------------------------------------------------------------------------------


        # ----------------------------------------------------------------------------------------------------------
        # ---------------------------- include toroidal velocity boundary conditions and update loc_list (section v)
        # ----------------------------------------------------------------------------------------------------------
        bc_u_list = bc_u_spherical( l, 'section_v' )
        if (bc_u_list is None):  # no bc needed in section v if inviscid
            pass
        else:
            for q in [0,1,2]:
                loc_list[q].append( bc_u_list[q] )
        # ----------------------------------------------------------------------------------------------------------






    if par.thermal == 1: # includes the heat equation

        # Submatrices here for nocurl have only 2 rows empty at the top
        # instead of 4 to make room for the thermal boundary conditions

        # --------------------------------------------------------------------------------------------------------------------------------------------------
        # -------------------------------------------------------------------------------------------------------------- A matrix, heat equation (section h)
        # --------------------------------------------------------------------------------------------------------------------------------------------------
        for k,l in enumerate(loc_top): # here use the l's from loc_top

            col0 = (rank*bpp + k )* ut.N1
            row = 2*nb*ut.N1 + col0

            # Poloidal velocity terms: -rʰ p uᵣ dS/dr -------------------------------------------------------------------
            # ----------------------------------------------------------------------- A, heat equation (section h), upol
            # ----------------------------------------------------------------------------------------------------------
            basecol = 0

            # Physics ------------------------------------
            mtx = op.thermal_advection(l,'h','upol',0)
            # --------------------------------------------
            col = basecol + col0

            loc_list = ut.packit( loc_list, mtx, row, col)

            if par.diff_rot :  # differential rotation terms of the heat equation (diff_rot.heat_block)

                # advection of s by the background rotation, Δl = 0, ±2 ------------------------------------------
                basecol = 2*nb*ut.N1
                for i in dr.dl_range('h','temp') :
                    if l+i in ll_flo[0] :
                        mtx = op.thermal_diffrot(l,'h','temp',i)
                        if np.isscalar(mtx[0]): continue
                        col = basecol + col0 + mtx[1] * ut.N1
                        loc_list = ut.packit( loc_list, mtx[0], row, col)

                if par.thermal_wind :  # advection of the thermal-wind entropy by u

                    basecol = 0  # poloidal part, Δl = 0, ±2, ..., ±(the highest degree of S_tw)
                    for i in dr.dl_range('h','upol') :
                        if l+i in ll_flo[0] :
                            mtx = op.thermal_diffrot(l,'h','upol',i)
                            if np.isscalar(mtx[0]): continue
                            col = basecol + col0 + mtx[1] * ut.N1
                            loc_list = ut.packit( loc_list, mtx[0], row, col)

                    basecol = nb*ut.N1  # toroidal part, Δl = ±1, ±3, ..., below the highest degree of S_tw
                    for i in dr.dl_range('h','utor') :
                        if l+i in ll_flo[1] :
                            mtx = op.thermal_diffrot(l,'h','utor',i)
                            if np.isscalar(mtx[0]): continue
                            col = basecol + col0 + mtx[1] * ut.N1
                            loc_list = ut.packit( loc_list, mtx[0], row, col)


            # entropy (s) terms: ThermaD rʰ ∇⋅(κ p ∇s) -----------------------------------------------------------------
            # ----------------------------------------------------------------------- A, heat equation (section h), temp
            # ----------------------------------------------------------------------------------------------------------
            if par.ThermaD > 0:
                basecol = 2*nb*ut.N1

                # Physics ----------------------------
                mtx = op.thermal_diffusion(l,'h','',0)
                # ------------------------------------
                col = basecol + col0

                loc_list = ut.packit(loc_list, mtx, row, col)

            # time derivative for forced problems: A - i wf B with B = +entropy here (B = -inertia in the momentum rows)
            if par.forcing != 0:
                mtx = -1j*ut.wf*op.entropy(l,'h','',0)
                col = 2*nb*ut.N1 + col0
                loc_list = ut.packit(loc_list, mtx, row, col)



            # ----------------------------------------------------------------------------------------------------------
            # -------------------------------------------------- include thermal boundary conditions and update loc_list
            # ----------------------------------------------------------------------------------------------------------
            bc_theta_list = bc_theta_spherical( l )
            if bc_theta_list is not None:
                for q in [0,1,2]:
                    loc_list[q].append( bc_theta_list[q] )
            # ----------------------------------------------------------------------------------------------------------






    if par.magnetic == 1:  # NEW (2026-10-28): the induction equation, sections f (r² r̂⋅) and g (r² r̂⋅∇×), after h

        # --------------------------------------------------------------------------------------------------------------------------------------------------
        # ----------------------------------------------------------------------------------------------------- A matrix, induction equation (sections f, g)
        # --------------------------------------------------------------------------------------------------------------------------------------------------
        # A holds the right-hand side: induction ∇×(u×B0) and diffusion MagnetD ∇²b (iω_f b would go with forcing, not allowed yet)
        for sec, comp, loc_mag in [ ('f', 'bpol', loc_mag_f), ('g', 'btor', loc_mag_g) ]:
            for k,l in enumerate(loc_mag):

                col0 = (rank*bpp + k )* ut.N1
                row  = ut.offset[sec] + col0

                # induction by the flow, poloidal (upol) and toroidal (utor) columns
                for basecol, ucomp, lls in [ (0, 'upol', ll_flo[0]), (ut.n, 'utor', ll_flo[1]) ]:
                    for i in ut.mag_dl:   # poloidal and toroidal B0 couplings (operators.induction returns 0 for the others; NEW 2026-10-30: ut.mag_dl)
                        if l+i in lls:
                            mtx = op.induction(l, sec, ucomp, i)
                            if np.isscalar(mtx[0]): continue
                            col = basecol + col0 + mtx[1] * ut.N1
                            loc_list = ut.packit( loc_list, mtx[0], row, col)

                # NEW (2026-10-30): induction by the background flow ∇×(U0×b), from the poloidal (F, section f) and toroidal
                # (G, section g) field: F→f, G→g at even Δl, F→g at odd Δl (diff_rot.induction_dl_range)
                if par.diff_rot:
                    for bcomp, bsec, lls in [ ('bpol', 'f', ll_mag[0]), ('btor', 'g', ll_mag[1]) ]:
                        for i in dr.induction_dl_range(sec, bcomp):
                            if l+i in lls:
                                mtx = op.differential_rotation_induction(l, sec, bcomp, i)
                                if np.isscalar(mtx[0]): continue
                                col = ut.offset[bsec] + col0 + mtx[1] * ut.N1
                                loc_list = ut.packit( loc_list, mtx[0], row, col)

                # magnetic diffusion
                mtx = -1 * op.magnetic_diffusion(l, sec, comp, 0)
                loc_list = ut.packit( loc_list, mtx, row, row)

                # boundary-condition rows: insulating walls, or the matching with a conducting inner core at the ICB
                bc_b_list = bc_b_spherical(l, sec)
                for q in [0,1,2]:
                    loc_list[q].append( bc_b_list[q] )
                if ut.cic:
                    bc_b_list = bc_b_cic(l, sec)
                    for q in [0,1,2]:
                        loc_list[q].append( bc_b_list[q] )

        if ut.cic:  # NEW (2026-10-28): conducting inner core, sections fic, gic: A = -(diffusion), its bc row is the ICB matching
            for sec, comp, loc_mag in [ ('fic', 'bpol_ic', loc_mag_f), ('gic', 'btor_ic', loc_mag_g) ]:
                for k,l in enumerate(loc_mag):
                    row = ut.offset[sec] + ( rank*bpp + k )* ut.Nic
                    mtx = -1 * op.magnetic_diffusion(l, sec, comp, 0)
                    if par.diff_rot:   # NEW (2026-10-30): the core co-rotates with ΔΩ(ricb) = c (rigid: background.magnetic_diffrot)
                        mtx = mtx + 1j*par.m*par.Gaspard*dr.rigid_ricb()[0]*op.b(l, sec, comp, 0)   # -(-i m G c b), the A sign
                    loc_list = ut.packit( loc_list, mtx, row, row)
                    bc_b_list = bc_b_cic(l, sec)
                    for q in [0,1,2]:
                        loc_list[q].append( bc_b_list[q] )


    # ------------------------------------------------------------------------------------------------------------------ A matrix assembly
    A = gather_csr(comm, loc_list, complex)  # full A on rank 0, None elsewhere
    del loc_list

    if rank == 0:

        if par.forcing == 0:
            Anorm = ssl.norm(A)
            A.data *= 1/Anorm  # in place, no copy of A (same arithmetic as scipy's A/Anorm)

        toc = timer()
        print('--------------------------------------------')
        print(' Matrix A assembled in', '{: 4.3f}'.format(toc-tic), 'seconds')
        tic = timer()
        np.savez('A.npz', data=A.data, indices=A.indices, indptr=A.indptr, shape=A.shape)
        toc = timer()
        print(' Matrix A written to disk in', '{: 4.3f}'.format(toc-tic), 'seconds')
        print('--------------------------------------------')
        del A

    comm.Barrier()


    if par.forcing in (0, 11):
        # ---------------------------------------------------------------------------------------------------------------------------------------------------------
        # --------------------------------------------------------------------------------------------------------------- B matrix, no forcing (eigenvalue problem)
        # ---------------------------------------------------------------------------------------------------------------------------------------------------------
        '''
        Builds the right hand side B matrix to solve
        the generalized eigenvalue problem A.x = lambda.B.x
        With forcing = 11 B is written too, not normalised, for the frequency scan of solve.py:
        the forced matrix at frequency w is A - i (w - forcing_frequency) B.
        '''

        if rank == 0:
            tic = timer()
        loc_list = [[], [], []]  # this rank's B entries, as lists of (data, row, col) arrays


        # ----------------------------------------------------------------------- B matrix, 2curl (hydro), section u
        for k,l in enumerate(loc_top):

            row = ( rank*bpp + k )* ut.N1
            col = row

            mtx = -op.inertia(l,'u','upol',0)

            loc_list = ut.packit(loc_list, mtx, row, col)


        # ----------------------------------------------------------------------- B matrix, 1curl (hydro), section v
        for k,l in enumerate(loc_bot):

            row = nb*ut.N1 + ( rank*bpp + k )* ut.N1
            col = row

            mtx = -op.inertia(l,'v','utor',0)

            loc_list = ut.packit(loc_list, mtx, row, col)





        if par.thermal == 1: # adds rʰ p (d/dt) s in the heat (entropy) equation to matrix B

            # ------------------------------------------------------------------- B, theta_pol, nocurl (heat), section h
            for k,l in enumerate(loc_top):  # loc_top here because theta
                                            # follows the same symmetry as u
                row = 2*nb*ut.N1 + ( rank*bpp + k )* ut.N1
                col = row

                mtx = op.entropy(l,'h','', 0)

                loc_list = ut.packit(loc_list, mtx, row, col)






        if par.magnetic == 1:  # NEW (2026-10-28): -(d/dt) b in the induction equation, B = -b (as -inertia in the momentum rows)

            for sec, comp, loc_mag in [ ('f', 'bpol', loc_mag_f), ('g', 'btor', loc_mag_g) ]:
                for k,l in enumerate(loc_mag):
                    row = ut.offset[sec] + ( rank*bpp + k )* ut.N1
                    mtx = -op.b(l, sec, comp, 0)
                    loc_list = ut.packit(loc_list, mtx, row, row)

            if ut.cic:  # NEW (2026-10-28): the inner-core field, B = -b as in f, g (conductive_IC has B = +b, A = +diffusion there)
                for sec, comp, loc_mag in [ ('fic', 'bpol_ic', loc_mag_f), ('gic', 'btor_ic', loc_mag_g) ]:
                    for k,l in enumerate(loc_mag):
                        row = ut.offset[sec] + ( rank*bpp + k )* ut.Nic
                        mtx = -op.b(l, sec, comp, 0)
                        loc_list = ut.packit(loc_list, mtx, row, row)


        # ---------------------------------------------------------------------- B matrix assembly
        B = gather_csr(comm, loc_list, float)  # full B on rank 0, None elsewhere
        del loc_list

        if rank == 0:
            if par.forcing == 0:
                B.data *= 1/Anorm  # in place, no copy of B (same arithmetic as scipy's B/Anorm)

            toc = timer()
            print(' Matrix B assembled in', '{: 4.3f}'.format(toc-tic), 'seconds')
            tic = timer()

            np.savez('B.npz', data=B.data, indices=B.indices, indptr=B.indptr, shape=B.shape)
            toc = timer()
            print(' Matrix B written to disk in', '{: 4.3f}'.format(toc-tic), 'seconds')
            print('--------------------------------------------')

        comm.Barrier()



    if rank == 0:
        print(' Total time (incl. imports):', '{: 4.3f}'.format(timer()-t_start), 'seconds')


    # ------------------------------------------------------------------------------------------------------------------ done!
    return 0



def gather_csr(comm, loc_list, dtype):
    '''
    Gathers the matrix entries of all ranks on rank 0 and returns the full
    ut.sizmat x ut.sizmat CSR matrix there (None on the other ranks).
    loc_list is this rank's [data, row, col] as built with ut.packit.
    Uses Gatherv with the exact count per rank, so nothing is padded or filtered afterwards.
    '''
    rank = comm.Get_rank()
    data, row, col = ut.unpackit(loc_list)  # join the per-block arrays once
    data = np.ascontiguousarray(data, dtype=dtype)
    row  = np.ascontiguousarray(row,  dtype=np.int32)  # ut.sizmat is far below 2**31
    col  = np.ascontiguousarray(col,  dtype=np.int32)

    counts = comm.gather(data.size, root=0)
    fdat = frow = fcol = None
    if rank == 0:
        counts = np.array(counts, dtype=np.int64)
        displs = np.concatenate([[0], np.cumsum(counts)[:-1]])
        fdat = np.empty(counts.sum(), dtype=dtype)
        frow = np.empty(counts.sum(), dtype=np.int32)
        fcol = np.empty(counts.sum(), dtype=np.int32)
        recv = lambda buf, mpitype: [buf, counts, displs, mpitype]
    else:
        recv = lambda buf, mpitype: None

    mpitype = MPI.DOUBLE_COMPLEX if np.dtype(dtype) == np.complex128 else MPI.DOUBLE
    comm.Gatherv([data, mpitype], recv(fdat, mpitype), root=0)
    comm.Gatherv([row, MPI.INT],  recv(frow, MPI.INT),  root=0)
    comm.Gatherv([col, MPI.INT],  recv(fcol, MPI.INT),  root=0)
    del data, row, col

    if rank == 0:
        if frow.size and (frow.min() < 0 or fcol.min() < 0 or frow.max() >= ut.sizmat or fcol.max() >= ut.sizmat):
            raise ValueError('matrix entry outside 0..sizmat-1')
        return ss.csr_matrix((fdat, (frow, fcol)), shape=(ut.sizmat, ut.sizmat), dtype=dtype)
    return None



def bc_u_spherical(l,loc):
    '''
    Spherical boundary conditions for the velocity field,
    either no-penetration (for the inviscid case), stress-free or no-slip.
    '''
    inviscid = (par.ViscosD == 0) #boolean

    R  = ut.rcmb
    Ri = par.ricb

    # Log density and up to 2nd derivative at the surface
    lhb0 = bv.lhb0
    lhb1 = bv.lhb1
    lhb2 = bv.lhb2

    if par.ricb > 0:
        # Log density and up to 2nd derivative at the ICB
        lha0 = bv.lha0
        lha1 = bv.lha1
        lha2 = bv.lha2

    L = l*(l+1.)

    if inviscid:
        num_rows_u = 1
        num_rows_v = 0
    else:
        num_rows_u = int(2 + 2*np.sign(par.ricb))  # 2 if no IC, 4 if present
        num_rows_v = int(1 + 1*np.sign(par.ricb))  # 1 if no IC, 2 if present

    ixu = ( par.m + 1 - ut.s )%2  #
    ixv = ( par.m + ut.s )%2
    if par.ricb > 0 :
        Tbu = bv.Tb
        Tbv = bv.Tb
    else:
        Tbu = bv.Tb[ixu::2,:]
        Tbv = bv.Tb[ixv::2,:]

    if loc == 'section_u':  # 2curl eqs

        out = ss.dok_matrix((num_rows_u, ut.N1),dtype=complex)

        if inviscid:

            out[ 0,:] = Tbu[:,0]  # P=0, no penetration

        else:

            if par.bco in [0, 2]: # stress-free cmb, do not use this if density is zero at the surface

                if par.bco == 0:  # impenetrable cmb
                    out[ 0,:] = Tbu[:,0]
                elif par.bco == 2:    # zero radial stress at the cmb
                    out[ 0,:] = Tbu[:,0]*(lhb1*R-3) + Tbu[:,1]*3*R

                # zero consoidal stress at the cmb
                out[ 1,:] = Tbu[:,2]*(R**2) + Tbu[:,1]*(R**2)*lhb1 + Tbu[:,0]*( (R**2)*lhb2 + (L-2) - R*lhb1 )

            elif par.bco == 1: # no-slip cmb

                out[ 0,:] = Tbu[:,0]  # P=0
                out[ 1,:] = Tbu[:,1] + Tbu[:,0]*( lhb1 + (1/R) )

            if par.ricb > 0:

                if par.bci in [0, 2]:  # stress-free icb

                    if par.bci == 0:    # impenetrable icb
                        out[ 2,:] =   bv.Ta[:,0]  # P=0
                    elif par.bci == 2:  # zero radial stress at the icb
                        out[ 2,:] = bv.Ta[:,0]*(lha1*Ri-3) + bv.Ta[:,1]*3*Ri

                    # zero consoidal stress at the icb
                    out[ 3,:] = bv.Ta[:,2]*(Ri**2) + bv.Ta[:,1]*(Ri**2)*lha1 + bv.Ta[:,0]*( (Ri**2)*lha2 + (L-2) - Ri*lha1 )

                elif par.bci == 1: # no-slip icb
                    out[ 2,:] = bv.Ta[:,0]  # P =0
                    out[ 3,:] = bv.Ta[:,1] + bv.Ta[:,0]*( lha1 + (1/Ri) )

        row0 = int(ut.N1*(l-ut.m_top)/2)
        col0 = int(ut.N1*(l-ut.m_top)/2)

    elif loc == 'section_v': # 1curl eqs

        if inviscid:

            return None

        else:

            out = ss.dok_matrix((num_rows_v, ut.N1),dtype=complex)

            if   par.bco in [0, 2]: # zero toroidal stress at the cmb
                out[ 0,:] = R * Tbv[:,1] - Tbv[:,0]  # R*T'-T=0

            elif par.bco == 1: # no-slip cmb
                out[ 0,:] = Tbv[:,0]  # T=0

            if par.ricb > 0 :

                if   par.bci in [0, 2]: # zero toroidal stress at the icb
                    out[ 1,:] = Ri * bv.Ta[:,1] - bv.Ta[:,0]

                elif par.bci == 1: # no-slip icb
                    out[ 1,:] = bv.Ta[:,0]  # T=0

            row0 = ut.n + int( ut.N1*(l-ut.m_bot)/2 )
            col0 = ut.n + int( ut.N1*(l-ut.m_bot)/2 )


    out = out.tocoo()
    out2 = [out.data, out.row + row0, out.col + col0]

    return out2



def bc_b_spherical(l, sec):
    '''
    NEW (2026-10-28): boundary conditions for the magnetic field at insulating walls (conductive_IC's bc_b_cmb, bc_b_icb), on
    the two bc rows of each block: row 0 at the outer boundary (l+1) f + r f' = 0 and g = 0, row 1 at the inner boundary
    l f - r f' = 0 and g = 0 (b matches a potential field outside the shell, and inside it with ricb > 0).
    '''
    inner = (par.ricb > 0) and not ut.cic   # NEW (2026-10-28): a full sphere has the outer row only, a conducting core bc_b_cic's
    out = ss.dok_matrix((1 + int(par.ricb > 0), ut.N1), dtype=complex)
    if par.ricb > 0:
        Tb = bv.Tb
    else:   # one parity of Chebyshev polynomials per section (as conductive_IC's bc_b_cmb): f has the parity of vF = symmB0 vP
        ixf = ( par.m + ut.s )%2 if ut.symmB0 == -1 else ( par.m + 1 - ut.s )%2
        Tb = bv.Tb[(ixf if sec == 'f' else 1 - ixf)::2, :]

    if sec == 'f':
        out[ 0,:] = (l+1) * Tb[:,0] + ut.rcmb * Tb[:,1]
        if inner:
            out[ 1,:] = l * bv.Ta[:,0] - par.ricb * bv.Ta[:,1]
    elif sec == 'g':
        out[ 0,:] = Tb[:,0]
        if inner:
            out[ 1,:] = bv.Ta[:,0]

    # the first l of each section's block list: f has the l's of T (symmB0 = -1) or of P (symmB0 = 1), g the others
    lfirst = ut.m_bot if (sec == 'f') == (ut.symmB0 == -1) else ut.m_top
    row0 = ut.offset[sec] + int( ut.N1*(l - lfirst)/2 )

    out = out.tocoo()
    return [out.data, out.row + row0, out.col + row0]



def bc_b_cic(l, sec):
    '''
    NEW (2026-10-28): the matching of the fluid's field with a conducting inner core at the ICB (conductive_IC's bc_b_cic), one
    row in each of the four sections: in f (its row 1) [n⋅b] f_o - f_i = 0; in g (its row 1) the toroidal [n×E]
    (g + r g')_o - η_i (g + r g')_i = 0 with η_i = 1/(mu_i2o sigma_i2o); in fic (its row 0) the toroidal [n×b/μ]
    mu_i2o (f + r f')_o - (f + r f')_i = 0; in gic (its row 0) the consoidal [n×b/μ] mu_i2o g_o - g_i = 0. As in
    conductive_IC the continuity of η∇²_l f is not imposed: with b_r continuous it follows from the radial induction equation
    on both sides, since u = 0 at the no-slip ICB.
    '''
    ric     = par.ricb
    eta_i2o = 1/( par.mu_i2o * par.sigma_i2o )
    lfirst  = ut.m_bot if ((sec in ['f', 'fic']) == (ut.symmB0 == -1)) else ut.m_top   # as in bc_b_spherical
    k       = int( (l - lfirst)/2 )   # block index of l in its section

    outoc = ss.dok_matrix((1, ut.N1 ), dtype=complex)
    outic = ss.dok_matrix((1, ut.Nic), dtype=complex)

    if sec == 'f':
        row0 = ut.offset['f'] + k*ut.N1 + 1
        colo, coli = ut.offset['f'] + k*ut.N1, ut.offset['fic'] + k*ut.Nic
        outoc[0,:] =  bv.Ta[:,0]
        outic[0,:] = -bv.Tbfic[:,0]
    elif sec == 'g':
        row0 = ut.offset['g'] + k*ut.N1 + 1
        colo, coli = ut.offset['g'] + k*ut.N1, ut.offset['gic'] + k*ut.Nic
        outoc[0,:] =  bv.Ta[:,0] + ric*bv.Ta[:,1]
        outic[0,:] = -eta_i2o * ( bv.Tbgic[:,0] + ric*bv.Tbgic[:,1] )
    elif sec == 'fic':
        row0 = ut.offset['fic'] + k*ut.Nic
        colo, coli = ut.offset['f'] + k*ut.N1, ut.offset['fic'] + k*ut.Nic
        outoc[0,:] = par.mu_i2o * ( bv.Ta[:,0] + ric*bv.Ta[:,1] )
        outic[0,:] = -( bv.Tbfic[:,0] + ric*bv.Tbfic[:,1] )
    elif sec == 'gic':
        row0 = ut.offset['gic'] + k*ut.Nic
        colo, coli = ut.offset['g'] + k*ut.N1, ut.offset['gic'] + k*ut.Nic
        outoc[0,:] = par.mu_i2o * bv.Ta[:,0]
        outic[0,:] = -bv.Tbgic[:,0]

    outoc = outoc.tocoo()
    outic = outic.tocoo()
    return [ np.concatenate([outoc.data, outic.data]), np.concatenate([outoc.row + row0, outic.row + row0]),
             np.concatenate([outoc.col + colo, outic.col + coli]) ]



