def gather_csr(comm, loc_list, dtype):
    '''
    Gathers the matrix entries of all ranks on rank 0 and returns the full
    ut.sizmat x ut.sizmat CSR matrix there (None on the other ranks).
    loc_list is this rank's [data, row, col] as built with ut.packit.
    Uses Gatherv with the exact count per rank, so nothing is padded or filtered afterwards.
    '''
    rank = comm.Get_rank()
    data, row, col = ut.unpackit(loc_list)  # join the per-block arrays once
    data = np.ascontiguousarray(data, dtype=dtype)
    row  = np.ascontiguousarray(row,  dtype=np.int32)  # ut.sizmat is far below 2**31
    col  = np.ascontiguousarray(col,  dtype=np.int32)

    counts = comm.gather(data.size, root=0)
    fdat = frow = fcol = None
    if rank == 0:
        counts = np.array(counts, dtype=np.int64)
        displs = np.concatenate([[0], np.cumsum(counts)[:-1]])
        fdat = np.empty(counts.sum(), dtype=dtype)
        frow = np.empty(counts.sum(), dtype=np.int32)
        fcol = np.empty(counts.sum(), dtype=np.int32)
        recv = lambda buf, mpitype: [buf, counts, displs, mpitype]
    else:
        recv = lambda buf, mpitype: None

    mpitype = MPI.DOUBLE_COMPLEX if np.dtype(dtype) == np.complex128 else MPI.DOUBLE
    comm.Gatherv([data, mpitype], recv(fdat, mpitype), root=0)
    comm.Gatherv([row, MPI.INT],  recv(frow, MPI.INT),  root=0)
    comm.Gatherv([col, MPI.INT],  recv(fcol, MPI.INT),  root=0)
    del data, row, col

    if rank == 0:
        if frow.size and (frow.min() < 0 or fcol.min() < 0 or frow.max() >= ut.sizmat or fcol.max() >= ut.sizmat):
            raise ValueError('matrix entry outside 0..sizmat-1')
        return ss.csr_matrix((fdat, (frow, fcol)), shape=(ut.sizmat, ut.sizmat), dtype=dtype)
    return None



def lifted_rhs(A, x):
    '''
    NEW (2026-11-08): forcings 1 and 8, the right-hand side b = -A 𝐱 on the interior rows of the fluid's equations (sections
    u, v, h, f, g, c) and 0 on every other row, for the known flow 𝐱 (utils.lifted_flow): the flow solved for is then
    𝐮' = 𝐮 - 𝐱, with 𝐮 the solution of the same equations with no force, whose walls move as 𝐱 does there, while 𝐮' meets
    the boundary rows of walls at rest. b holds the body force -(i w 𝐱 + 2 Gaspard 𝐳×𝐱 - (∇⋅𝛔(𝐱))/ρ₀ - 𝐅(𝐱)) (𝐅 the force
    of a differential rotation) and the induction and the advection of the entropy (and of the composition) by 𝐱, each in the
    curls and rows of A, so
    that 𝐮' + 𝐱 is exactly the flow with the walls moving (to round-off, whatever the background). The boundary rows of a
    block are those that the block's own time derivative (operators.inertia, entropy, b, composition) leaves empty at the top, where
    submatrices.py made room for them; the rows of the solids beyond the walls are boundary rows too.
    A is the matrix of the forced problem (i w B included, not normalised).
    '''
    def top_rows(mtx):   # the empty rows at the top of a block
        nnz = np.diff(ss.csr_matrix(mtx).indptr)
        return int(np.argmax(nnz > 0))
    lp, lt = ut.ell(par.m, par.lmax, par.symm)[:2]
    blocks = []   # (section, the block's time derivative)
    if par.hydro:
        blocks += [ ('u', op.inertia(lp[0], 'u', 'upol', 0)), ('v', op.inertia(lt[0], 'v', 'utor', 0)) ]
    if par.thermal:
        blocks += [ ('h', op.entropy(lp[0], 'h', '', 0)) ]
    if par.magnetic:
        lf, lg = ut.ell(par.m, par.lmax, ut.bsymm)[:2]
        blocks += [ ('f', op.b(lf[0], 'f', 'bpol', 0)), ('g', op.b(lg[0], 'g', 'btor', 0)) ]
    if par.compositional:   # (NEW 2026-11-08)
        blocks += [ ('c', op.composition(lp[0], 'c', '', 0)) ]
    interior = np.zeros(ut.sizmat, dtype=bool)
    for sec, mtx in blocks:
        nbc = top_rows(mtx)
        for k in range(int((par.lmax - par.m + 1)/2)):
            r0 = ut.offset[sec] + k*ut.N1
            interior[r0 + nbc: r0 + ut.N1] = True
    b = -(A @ x)
    b[~interior] = 0
    return b



def bc_u_spherical(l,loc):
    '''
    Spherical boundary conditions for the velocity field,
    either no-penetration (for the inviscid case), stress-free or no-slip.
    '''
    inviscid = (par.ViscosD == 0) #boolean

    R  = ut.rcmb
    Ri = par.ricb

    # Log density and up to 2nd derivative at the surface
    lhb0 = bv.lhb0
    lhb1 = bv.lhb1
    lhb2 = bv.lhb2

    if par.ricb > 0:
        # Log density and up to 2nd derivative at the ICB
        lha0 = bv.lha0
        lha1 = bv.lha1
        lha2 = bv.lha2

    L = l*(l+1.)

    if inviscid:
        num_rows_u = 1
        num_rows_v = 0
    else:
        num_rows_u = int(2 + 2*np.sign(par.ricb))  # 2 if no IC, 4 if present
        num_rows_v = int(1 + 1*np.sign(par.ricb))  # 1 if no IC, 2 if present

    ixu = ( par.m + 1 - ut.s )%2  #
    ixv = ( par.m + ut.s )%2
    if par.ricb > 0 :
        Tbu = bv.Tb
        Tbv = bv.Tb
    else:
        Tbu = bv.Tb[ixu::2,:]
        Tbv = bv.Tb[ixv::2,:]

    if loc == 'section_u':  # 2curl eqs

        out = ss.dok_matrix((num_rows_u, ut.N1),dtype=complex)

        if inviscid:

            out[ 0,:] = Tbu[:,0]  # P=0, no penetration

        else:

            if par.bco in [0, 2]: # stress-free cmb, do not use this if density is zero at the surface

                if par.bco == 0:  # impenetrable cmb
                    out[ 0,:] = Tbu[:,0]
                elif par.bco == 2:    # zero radial stress at the cmb
                    out[ 0,:] = Tbu[:,0]*(lhb1*R-3) + Tbu[:,1]*3*R

                # zero consoidal stress at the cmb
                out[ 1,:] = Tbu[:,2]*(R**2) + Tbu[:,1]*(R**2)*lhb1 + Tbu[:,0]*( (R**2)*lhb2 + (L-2) - R*lhb1 )

            elif par.bco == 1: # no-slip cmb

                out[ 0,:] = Tbu[:,0]  # P=0
                out[ 1,:] = Tbu[:,1] + Tbu[:,0]*( lhb1 + (1/R) )

            if par.ricb > 0:

                if par.bci in [0, 2]:  # stress-free icb

                    if par.bci == 0:    # impenetrable icb
                        out[ 2,:] =   bv.Ta[:,0]  # P=0
                    elif par.bci == 2:  # zero radial stress at the icb
                        out[ 2,:] = bv.Ta[:,0]*(lha1*Ri-3) + bv.Ta[:,1]*3*Ri

                    # zero consoidal stress at the icb
                    out[ 3,:] = bv.Ta[:,2]*(Ri**2) + bv.Ta[:,1]*(Ri**2)*lha1 + bv.Ta[:,0]*( (Ri**2)*lha2 + (L-2) - Ri*lha1 )

                elif par.bci == 1: # no-slip icb
                    out[ 2,:] = bv.Ta[:,0]  # P =0
                    out[ 3,:] = bv.Ta[:,1] + bv.Ta[:,0]*( lha1 + (1/Ri) )

        row0 = int(ut.N1*(l-ut.m_top)/2)
        col0 = int(ut.N1*(l-ut.m_top)/2)

    elif loc == 'section_v': # 1curl eqs

        if inviscid:

            return None

        else:

            out = ss.dok_matrix((num_rows_v, ut.N1),dtype=complex)

            if   par.bco in [0, 2]: # zero toroidal stress at the cmb
                out[ 0,:] = R * Tbv[:,1] - Tbv[:,0]  # R*T'-T=0

            elif par.bco == 1: # no-slip cmb
                out[ 0,:] = Tbv[:,0]  # T=0

            if par.ricb > 0 :

                if   par.bci in [0, 2]: # zero toroidal stress at the icb
                    out[ 1,:] = Ri * bv.Ta[:,1] - bv.Ta[:,0]

                elif par.bci == 1: # no-slip icb
                    out[ 1,:] = bv.Ta[:,0]  # T=0

            row0 = ut.n + int( ut.N1*(l-ut.m_bot)/2 )
            col0 = ut.n + int( ut.N1*(l-ut.m_bot)/2 )


    out = out.tocoo()
    out2 = [out.data, out.row + row0, out.col + col0]

    return out2



def bc_u_centrifugal(l, loc, ll_flo):
    '''
    NEW (2026-11-05, phase 2): with centrifugal = 1 and viscosity, the metric parts of the stress-free rows of bc_u_spherical
    (zero tangential traction on the deformed walls; centrifugal.wall_dissipative_rows): in the same rows (section u: row 1
    at the outer wall, row 3 at the inner one; section v: row 0 outside, row 1 inside), entries on P, P', P'' and T, T' of the
    degrees l, l ± 2 (the same kind as the row) and l ± 1 (the other), each with its Chebyshev parity in a full sphere. The
    impenetrable and no-slip rows need none (w_r = 0 and w = 0 are u⋅n = 0 and u = 0).
    '''
    sec = 'u' if loc == 'section_u' else 'v'
    walls = ([('outer', 1 if sec == 'u' else 0, bv.Tb)] if par.bco == 0 else []) + \
            ([('inner', 3 if sec == 'u' else 1, bv.Ta)] if (par.ricb > 0 and par.bci == 0) else [])
    ix = {'P': ( par.m + 1 - ut.s )%2, 'T': ( par.m + ut.s )%2}   # the Chebyshev parities of P and T (as bc_u_spherical)
    lfirst = {'P': ut.m_top, 'T': ut.m_bot}
    base = {'P': 0, 'T': ut.n}
    row0 = base['P' if sec == 'u' else 'T'] + int( ut.N1*(l - lfirst['P' if sec == 'u' else 'T'])/2 )
    data, rows, cols = [], [], []
    for wall, rr, T in walls:
        B, W = cf.wall_dissipative_rows(wall)
        for X, lls, kinds in (('P', ll_flo[0], ('P0', 'P1', 'P2')), ('T', ll_flo[1], ('T0', 'T1'))):
            Tc = T if par.ricb > 0 else T[ix[X]::2, :]
            for dl in range(-B, B + 1):
                k = l + dl
                if k not in lls:
                    continue
                vec = 0
                for kind in kinds:
                    c = cf._lookup(W[(sec, kind)], l, par.m, dl) if (sec, kind) in W else 0
                    if c != 0:
                        vec = vec + c*Tc[:, int(kind[1])]
                if np.isscalar(vec):
                    continue
                nz = np.nonzero(vec)[0]
                data.append(vec[nz])
                rows.append(np.full(nz.size, row0 + rr))
                cols.append(base[X] + int( ut.N1*(k - lfirst[X])/2 ) + nz)
    if not data:
        return [np.zeros(0), np.zeros(0, dtype=int), np.zeros(0, dtype=int)]
    return [np.concatenate(data), np.concatenate(rows), np.concatenate(cols)]



_sheet_mats = {}

def bc_u_sheet(l, sec):
    '''
    NEW (2026-11-07, phase 6c): the push of B0's current sheet at a slipping wall (background.sheet_push) in the stress rows
    of the degree l, section sec 'u' (P_l) or 'v' (T_l), as [data, row, col]. Where B0 ends at the wall in a current sheet
    on the fluid's side (background.sheet_jump: its tangential part jumps by ΔB0_t to the field beyond), the sheet, of current
    K0 = ∓r̂ × ΔB0_t at the outer and the inner wall, pushes the fluid with Hendrik K0×b, whose part along the wall is
    ∓Hendrik b_r ΔB0_t per area (b is continuous across the sheet). The viscous stress of the fluid at the wall takes it, as
    it takes a drag (topo.rows), in one form at both walls: the tangential stress, viscous and Maxwell, is continuous
    through the sheet and a slipping wall, and the Maxwell stress Hendrik (B0_r b_t + b_r B0_t) is larger by Hendrik b_r ΔB0_t
    on the fluid's side, so that
        ViscosD ρ0 ν [r ∂r(u_t/r) + ∇₁u_r/r] = -Hendrik b_r ΔB0_t,
    and the stress rows of bc_u_spherical, r² (section u: the second row of the outer wall, the fourth of the inner one) and
    r (section v: the first and the second) times the parts of [r ∂r(u_t/r) + ∇₁u_r/r] on ∇₁Y_l and ∇₁Y_l × r̂, gain r² q
    and r q times the same parts of b_r ΔB0_t, q = Hendrik/(ViscosD ρ0 ν) at the wall (ν the viscosity profile). Those
    parts come from the angular algebra (mag_algebra._vcross): b_r ΔB0_t = (r̂ × ΔB0_t) × b_r r̂, with r̂ × ΔB0_t = -k_n P_n'
    sinθ θ̂ for the toroidal jump (B0_phi = k_n P_n' sinθ) and -a_n P_n' sinθ φ̂ for the poloidal one (ΔB0_t = a_n ∇₁Y_n),
    and b_r = L_k F_k/r: entries on F of every degree k with |k - l| <= nB + 1, its value at the wall. The normal part of
    the push, Hendrik ΔB0_t⋅b_t along the fluid's outward normal (the drop of the magnetic pressure Hendrik B0⋅b across the
    sheet), the wall takes (and the zero viscous radial stress of bco, bci = 2, which leaves out the pressure, leaves it out
    too).
    '''
    import angular
    import mag_algebra as ma
    import radial_profiles as rap
    m = par.m
    lp_u, lt_u = ut.ell(m, par.lmax, par.symm)[:2]
    lp_f = lt_u if ut.symmB0 == -1 else lp_u   # f has the l's of T (symmB0 = -1) or of P (symmB0 = 1)
    lfirst_f = ut.m_bot if ut.symmB0 == -1 else ut.m_top
    if par.ricb > 0:
        Tf = {'outer': bv.Tb, 'inner': bv.Ta}
    else:   # one parity of Chebyshev polynomials per section in a full sphere (as bc_b_spherical)
        ixf = ( m + ut.s )%2 if ut.symmB0 == -1 else ( m + 1 - ut.s )%2
        Tf = {'outer': bv.Tb[ixf::2, :]}
    data, rows, cols = [], [], []
    for wall, rr_u, rr_v in (('outer', 1, 0), ('inner', 3, 1)):
        if not bg.sheet_push(wall):
            continue
        r = ut.rcmb if wall == 'outer' else par.ricb
        if wall not in _sheet_mats:   # the parts of b_r ΔB0_t on S_l, T_l for b_r = L_k Y_k (columns k), once per wall
            tor, pol = bg.sheet_jump(wall)
            nB = max(list(tor) + list(pol))
            A = angular.Algebra.get(m, par.lmax + nB + 6)
            F = A.field(q=A.L)
            Ws = Wt = A.zero()
            for kind, jumps in (('st', tor), ('sp', pol)):
                for n, a in jumps.items():
                    dPn = np.polynomial.Legendre.basis(n).deriv()   # FIX (2026-11-08, phase 6e): a Legendre series
                    # (mag_algebra._poly_mats), not a Polynomial, whose coefficients grow as about (1 + √2)^n
                    V = ma._vcross(A, kind, -a*dPn, F)
                    Ws, Wt = Ws + V.s, Wt + V.t
            rw = np.array([float(r)])
            q = par.Hendrik/(par.ViscosD*float(np.exp(np.ravel(rap.logrhoX(rw, 0))[0]))*float(np.ravel(rap.viscoX(rw, 0))[0]))
            _sheet_mats[wall] = (Ws.tocsr(), Wt.tocsr(), nB, q)
        Ws, Wt, nB, q = _sheet_mats[wall]
        if sec == 'u':
            if l not in lp_u:
                continue
            row, W, fac = ut.offset['u'] + int(ut.N1*(l - ut.m_top)/2) + rr_u, Ws, r**2*q/r
        else:
            if l not in lt_u:
                continue
            row, W, fac = ut.offset['v'] + int(ut.N1*(l - ut.m_bot)/2) + rr_v, Wt, r*q/r
        T = Tf[wall]
        for k in range(max(l - nB - 1, 0), l + nB + 2):
            w = W[l, k] if k < W.shape[1] else 0
            if w == 0 or k not in lp_f:
                continue
            data.append( fac*w*T[:,0] )
            rows.append( np.full(T.shape[0], row) )
            cols.append( ut.offset['f'] + int(ut.N1*(k - lfirst_f)/2) + np.arange(T.shape[0]) )
    if not data:
        return [np.zeros(0, dtype=complex), np.zeros(0, dtype=int), np.zeros(0, dtype=int)]
    return [np.concatenate(data).astype(complex), np.concatenate(rows), np.concatenate(cols)]



